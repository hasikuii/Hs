#!/data/data/com.termux/files/usr/bin/sh
# install-adb-wrappers.sh — installs wrapper scripts for common Android
# system commands (pm, cmd, am, dumpsys, settings, input, svc) that
# automatically route through the ADB shell connection (UID 2000) when
# AdbService is running, and fall back to the direct system binary
# otherwise.
#
# WITHOUT these wrappers:
#   ~ $ pm list packages -3
#   cmd: Failure calling service package: Failed transaction (2147483646)
#   → fails because Termux app UID (10123) can't call PackageManagerService
#
# WITH these wrappers:
#   ~ $ pm list packages -3
#   package:com.example.app
#   → works because the command is routed through the ADB shell (UID 2000)
#
# Usage:
#   sh /path/to/install-adb-wrappers.sh        # install
#   sh /path/to/install-adb-wrappers.sh remove # remove (restore originals)
#
# After install, the following commands in Termux will route through ADB:
#   pm, cmd, am, dumpsys, settings, input, svc
#
# Prerequisites:
#   - AdbService running (open Termux → ADB không dây → Pair → Connect)
#   - The `adb` command installed (see termux-adb.sh)

set -e

PREFIX="${PREFIX:-/data/data/com.termux/files/usr}"
BINDIR="$PREFIX/bin"
PKG="${TERMUX_ADB_PKG:-com.termux}"
RECEIVER="$PKG/.app.adb.AdbService\$AdbCommandReceiver"

WRAP_CMDS="pm cmd am dumpsys settings input svc"

# --- Remove mode ---
if [ "$1" = "remove" ]; then
    echo "Removing ADB wrappers..."
    for cmd in $WRAP_CMDS; do
        wrapper="$BINDIR/$cmd"
        orig="$BINDIR/${cmd}.orig"
        if [ -f "$wrapper" ] && head -1 "$wrapper" 2>/dev/null | grep -q "ADB-routed"; then
            rm -f "$wrapper"
            if [ -f "$orig" ]; then
                mv "$orig" "$wrapper"
                echo "  restored $cmd (from .orig)"
            else
                echo "  removed $cmd (no .orig to restore)"
            fi
        fi
    done
    echo "Done."
    exit 0
fi

# --- Install mode ---
echo "Installing ADB wrappers to $BINDIR ..."

mkdir -p "$BINDIR"

for cmd in $WRAP_CMDS; do
    wrapper="$BINDIR/$cmd"
    orig="$BINDIR/${cmd}.orig"

    if [ -f "$wrapper" ] && ! head -1 "$wrapper" 2>/dev/null | grep -q "ADB-routed"; then
        cp "$wrapper" "$orig"
        echo "  backed up existing $cmd → ${cmd}.orig"
    fi

    if [ "$cmd" = "pm" ]; then
        fallback="/system/bin/cmd package"
    else
        fallback="/system/bin/$cmd"
    fi

    cat > "$wrapper" << WRAPPER_EOF
#!/data/data/com.termux/files/usr/bin/sh
# $cmd — ADB-routed wrapper (UID 2000 when AdbService is running)
# Falls back to $fallback if ADB service is not running.
# Auto-generated by install-adb-wrappers.sh

OUTFILE="/tmp/adb_out_\$\$.txt"
rm -f "\$OUTFILE"

am broadcast -a com.termux.adb.RUN_COMMAND -n "$RECEIVER" \\
    --es command "shell:$cmd \$*" \\
    --es outfile "\$OUTFILE" >/dev/null 2>&1

i=0
while [ \$i -lt 50 ]; do
    [ -f "\$OUTFILE" ] && break
    i=\$((i + 1))
    sleep 0.1
done

if [ -f "\$OUTFILE" ]; then
    cat "\$OUTFILE"
    rm -f "\$OUTFILE"
    exit 0
fi

rm -f "\$OUTFILE"
exec $fallback "\$@"
WRAPPER_EOF

    chmod +x "$wrapper"
    echo "  installed $cmd → routes through ADB shell (fallback: $fallback)"
done

echo ""
echo "Done! Installed wrappers for: $WRAP_CMDS"
echo ""
echo "Now you can run these commands directly in Termux:"
echo "  pm list packages -3"
echo "  pm grant com.example.app android.permission.DUMP"
echo "  dumpsys activity activities | head -20"
echo "  settings get secure android_id"
echo "  am start -n com.example.app/.MainActivity"
echo ""
echo "If ADB service is not running, commands fall back to direct"
echo "system binary (may fail with permission errors)."
echo ""
echo "To remove wrappers and restore originals:"
echo "  sh \$0 remove"
